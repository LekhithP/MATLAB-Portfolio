A=[2.4117 0.6557 0.6787 0.6555;
   0.9157 1.8804 0.7577 0.1712;
   0.7922 0.8491 3.0905 0.7060;
   0.9595 0.9340 0.3922 2.3175];
B=0.5*(A+A'); 
xs=[1;2;3;4];
b=B*xs;
x0=zeros(4,1); 
iter=40;
[xJ,residualJ]=helper.j(B,b,x0,iter);
[xGS,residualGS]=helper.gs(B,b,x0,iter);
[xSOR,residualSOR]=helper.sor(B,b,x0,1.5,iter);
figure;
plot(log(residualJ));
title('Jacobi'); 
xlabel('k'); 
grid on;
figure;
plot(log(residualGS));
title('Gauss-Seidel');
xlabel('k');
grid on;
figure;
plot(log(residualSOR));
title('SOR');
xlabel('k');
grid on;
w1=linspace(0.5,2,151);
r20=zeros(size(w1));
for i=1:length(w1)
    [xt,~]=helper.sor(B,b,x0,w1(i),20);
    r20(i)=norm(b-B*xt);
end
[~,mi]=min(r20);
disp(['Optimal w = ', num2str(w1(mi),'%.2f')]);
figure;
plot(w1,log(r20));
title('P3 log||r_{20}|| vs \omega');
xlabel('\omega');
grid on;